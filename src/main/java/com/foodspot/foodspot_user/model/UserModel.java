package com.foodspot.foodspot_user.model;

import org.springframework.data.annotation.Id;
import org.springframework.data.mongodb.core.index.Indexed;
import org.springframework.data.mongodb.core.mapping.Document;
import java.time.LocalDateTime;

@Document(collection = "User")
public class UserModel {
    
    @Id
    private String id;
    
    private String name;
    
    @Indexed(unique = true) // Instructs MongoDB to drop duplicate row entries
    private String email;
    
    private String password;

    private LocalDateTime createdAt;

    // Default Constructor required by Spring Data frameworks
    public UserModel() {}

    // Parameterized Constructor
    public UserModel(String name, String email, String password, LocalDateTime createdAt) {
        this.name = name;
        this.email = email;
        this.password = password;
        this.createdAt = createdAt;
    }

    // Getters and Setters
    public String getId() { return id; }
    public void setId(String id) { this.id = id; }

    public String getName() { return name; }
    public void setName(String name) { this.name = name; }

    public String getEmail() { return email; }
    public void setEmail(String email) { this.email = email; }

    public String getPassword() { return password; }
    public void setPassword(String password) { this.password = password; }

    public LocalDateTime getCreatedAt() { return createdAt; }
    public void setCreatedAt(LocalDateTime createdAt) { this.createdAt = createdAt; }
}